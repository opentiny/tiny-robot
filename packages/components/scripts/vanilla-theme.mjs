import { readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'

const source = new URL('../src/styles/variables.css', import.meta.url)
const target = new URL('../src/vanilla/theme/defaults.css', import.meta.url)
const entry = new URL('../src/vanilla/style.css', import.meta.url)
const references = (value) => [...value.matchAll(/var\(\s*(--[\w-]+)/g)].map((match) => match[1])

// New components register their CSS in the shared entry, which both builds consume.
function componentCSS() {
  const imports = []
  const ast = postcss.parse(readFileSync(entry, 'utf8'))
  for (const node of ast.nodes) {
    if (node.type === 'comment') continue
    if (node.type !== 'atrule' || node.name !== 'import')
      throw new Error('Vanilla style entry must contain local imports')
    const quote = node.params[0]
    if (!['"', "'"].includes(quote) || !node.params.endsWith(quote))
      throw new Error('Expected a quoted local CSS import')
    const path = node.params.slice(1, -1)
    if (!path.startsWith('./')) throw new Error('Vanilla styles must use relative CSS imports')
    const file = new URL(path, entry)
    if (file.href !== target.href) imports.push(readFileSync(file, 'utf8'))
  }
  return imports.join('\n')
}

/** Generate local fallbacks from the shared theme AST; never install global --tr-* variables. */
export function generateThemeCSS() {
  const ast = postcss.parse(readFileSync(source, 'utf8'), { from: fileURLToPath(source) })
  const common = new Map()
  const modes = { light: new Map(), dark: new Map() }
  ast.walkRules((rule) => {
    if (!rule.nodes.some((node) => node.type === 'decl' && node.prop.startsWith('--tr-'))) return
    const selectors = rule.selectors
    let destination
    if (selectors.length === 1 && selectors[0] === ':root') destination = common
    else if (
      selectors.includes("[data-tr-color-mode='light']") &&
      selectors.every((selector) => selector === ':root' || selector === "[data-tr-color-mode='light']")
    )
      destination = modes.light
    else if (selectors.length === 1 && selectors[0] === "[data-tr-color-mode='dark']") destination = modes.dark
    else throw new Error(`Unsupported shared theme selector: ${rule.selector}`)
    if (rule.parent.type !== 'root') throw new Error('Conditional shared theme rules need an explicit Vanilla mapping')
    rule.walkDecls(/^--tr-/, ({ prop, value }) => destination.set(prop, value))
  })

  const required = new Set()
  const componentAST = postcss.parse(componentCSS())
  componentAST.walkDecls(({ value }) => {
    for (const token of references(value)) {
      if (token.startsWith('--tr-') && !token.startsWith('--tr-quick-assist-') && !token.startsWith('--tr-vanilla-')) {
        required.add(token)
      }
    }
  })
  const output = postcss.root()
  output.append(
    postcss.comment({ text: 'Generated by scripts/vanilla-theme.mjs from shared TinyRobot tokens. Do not edit.' }),
  )
  for (const [mode, palette] of Object.entries(modes)) {
    const tokens = new Map([...common, ...palette])
    const selected = new Map()
    const visit = (token, path = []) => {
      if (path.includes(token)) throw new Error(`Circular theme token: ${[...path, token].join(' -> ')}`)
      if (selected.has(token)) return
      const value = tokens.get(token)
      if (value === undefined) throw new Error(`Missing ${mode} theme token: ${token}`)
      for (const dependency of references(value)) visit(dependency, [...path, token])
      selected.set(token, value)
    }
    for (const token of required) visit(token)
    componentAST.walkDecls(({ value }) => {
      for (const reference of references(value)) {
        if (
          reference.startsWith('--tr-vanilla-default-') &&
          !selected.has(reference.replace('--tr-vanilla-default-', '--tr-'))
        ) {
          throw new Error(`Unresolved Vanilla ${mode} fallback: ${reference}`)
        }
      }
    })
    const rule = postcss.rule({ selector: `[data-tr-vanilla][data-tr-vanilla-color-mode='${mode}']` })
    for (const [token, value] of selected) {
      rule.append(
        postcss.decl({
          prop: token.replace('--tr-', '--tr-vanilla-default-'),
          value: value.replace(
            /var\(\s*(--tr-[\w-]+)/g,
            (_, dependency) => `var(${dependency.replace('--tr-', '--tr-vanilla-default-')}`,
          ),
        }),
      )
    }
    output.append(rule)
  }
  return `${output.toString()}\n`
}

export function generateVanillaTheme() {
  const css = generateThemeCSS()
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== css) throw new Error('Vanilla theme is stale. Run generate:vanilla-theme.')
  } else if (readFileSafe(target) !== css) writeFileSync(target, css)
  return css
}

function readFileSafe(file) {
  try {
    return readFileSync(file, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
    return undefined
  }
}

export function vanillaStyle() {
  return `${generateVanillaTheme()}\n${componentCSS()}`
}

/** Keep source-based docs and browser fixtures in sync with shared token edits. */
export function vanillaThemePlugin() {
  return {
    name: 'tiny-robot-vanilla-theme',
    buildStart() {
      generateVanillaTheme()
    },
    configureServer(server) {
      server.watcher.add(fileURLToPath(source))
    },
    handleHotUpdate({ file }) {
      const vanillaDirectory = fileURLToPath(new URL('../src/vanilla/', import.meta.url))
      if (
        file === fileURLToPath(source) ||
        (file.startsWith(vanillaDirectory) && file.endsWith('.css') && file !== fileURLToPath(target))
      ) {
        generateVanillaTheme()
      }
    },
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) generateVanillaTheme()
