import { expect, test } from '../support/test'

for (const kind of ['chat', 'ui']) {
  test(`${kind} Scoped Slot 宿主视图、输入订阅与清理`, async ({ page }) => {
    await page.goto('/#/content/scoped-slots')
    await page.getByRole('combobox', { name: '组件', exact: true }).selectOption(kind)
    const host = page.locator('[data-scoped-host]')
    const toggle = (name: string) => page.getByRole('checkbox', { name: `${name} ·`, exact: false })
    for (const name of ['layout-empty-state', 'bubble-prefix', 'sender-footer']) await toggle(name).check()
    await expect(host.locator('.demo-scoped-header strong')).toHaveText('产品咨询')
    await expect(host.getByRole('heading', { name: '开始你的产品咨询', exact: true })).toBeVisible()
    await page.getByLabel('会话标题', { exact: true }).fill('接入排查')
    await expect(host.locator('.demo-scoped-header strong')).toHaveText('接入排查')
    await host.locator('[contenteditable=true]').fill('需要保留的草稿')
    await toggle('sender-content').check()
    const input = host.getByRole('textbox', { name: '自定义输入框', exact: true })
    await expect(input).toHaveValue('需要保留的草稿')
    await input.fill('宿主输入')
    await host.getByRole('button', { name: '插入追问', exact: true }).click()
    await expect(input).toHaveValue(/请详细说明/)
    await expect(input).toBeFocused()
    const draft = await input.inputValue()
    await page.getByRole('checkbox', { name: '显示欢迎区', exact: true }).uncheck()
    await expect(input).toHaveValue(draft)
    await expect(host.locator('.demo-message-meta')).toHaveText([/用户.*消息 0/, /助手.*消息 1/])
    await input.fill('Scoped Slot 提问')
    await host.locator('.tr-sender-submit-button').click()
    await expect(host.locator('.tr-bubble-list').getByText('Scoped Slot 提问', { exact: true })).toBeVisible()
    await expect(host.locator('.demo-message-meta')).toHaveCount(4)
    await expect(input).toHaveValue('')
    await host.locator('.demo-scoped-header').getByRole('button', { name: '新建会话', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: '显示欢迎区', exact: true })).toBeChecked()
    await expect(host.getByRole('heading', { name: '开始你的产品咨询', exact: true })).toBeVisible()
    await toggle('layout-header').uncheck()
    await toggle('sender-content').uncheck()
    await expect(host.locator('.chat-header__title')).toHaveText('接入排查')
    await expect(host.locator('[contenteditable=true]')).toBeVisible()
    await toggle('layout-header').check()
    await toggle('sender-content').check()
    await expect(input).toBeVisible()
    await test.info().attach('Scoped Slot 页面', { body: await page.screenshot(), contentType: 'image/png' })
    const old = await host.elementHandle()
    await page.getByRole('button', { name: '卸载元素', exact: true }).click()
    await expect(host).toHaveCount(0)
    await expect.poll(() => old!.evaluate((element) => element.childElementCount)).toBe(0)
    await page.getByRole('button', { name: '挂载元素', exact: true }).click()
    await expect(host.locator('.demo-scoped-header strong')).toHaveText('接入排查')
    await page
      .getByRole('navigation', { name: '能力导航' })
      .getByRole('link', { name: '公开方法', exact: true })
      .click()
    await expect(host).toHaveCount(0)
    await expect(page.getByTestId('ready-state')).toHaveText('已就绪')
  })
}
