import { expect, test } from '../support/test'

for (const kind of ['chat', 'ui']) {
  test(`${kind} 修改无关 Slot 设置保留输入选择范围`, async ({ page }) => {
    await page.goto('/#/content/scoped-slots')
    await page.getByRole('combobox', { name: '组件', exact: true }).selectOption(kind)
    const toggle = (name: string) => page.getByRole('checkbox', { name: `${name} ·`, exact: false })
    await toggle('layout-empty-state').check()
    await toggle('sender-content').check()
    await page.getByLabel('layout-empty-state 标题', { exact: true }).fill('输入状态检查')
    const input = page.locator('[data-scoped-host]').getByRole('textbox', { name: '自定义输入框', exact: true })
    await input.fill('保留输入状态')
    await expect(input).toHaveValue('保留输入状态')
    await input.evaluate((element: HTMLTextAreaElement) => element.setSelectionRange(0, 2))
    await page.getByLabel('bubble-content-footer 来源', { exact: true }).fill('接入指南')
    await expect
      .poll(() => input.evaluate((element: HTMLTextAreaElement) => [element.selectionStart, element.selectionEnd]))
      .toEqual([0, 2])
    await input.evaluate((element: HTMLTextAreaElement) => element.setSelectionRange(0, 2))
    await toggle('bubble-suffix').check()
    await expect
      .poll(() => input.evaluate((element: HTMLTextAreaElement) => [element.selectionStart, element.selectionEnd]))
      .toEqual([0, 2])
    await expect(input).toHaveValue('保留输入状态')
  })

  test(`${kind} 普通 Slot 可独立配置且互不影响`, async ({ page }) => {
    await page.goto('/#/content/ordinary-slots')
    await page.getByRole('combobox', { name: '组件', exact: true }).selectOption(kind)
    const host = page.locator('[data-slot-host]')
    const toggle = (name: string) => page.getByRole('checkbox', { name: `${name} ·`, exact: false })
    await expect(toggle('sender-header')).toBeChecked()
    await expect(toggle('welcome-footer')).not.toBeChecked()
    await page.getByLabel('咨询主题', { exact: true }).fill('独立配置')
    await expect(host.locator('[slot=sender-header]')).toContainText('独立配置')
    await toggle('welcome-footer').check()
    await page.getByLabel('welcome-footer 内容', { exact: true }).fill('欢迎咨询账号问题')
    await expect(host.locator('[slot=welcome-footer]')).toHaveText('欢迎咨询账号问题')
    await toggle('input-prefix').check()
    await page.getByLabel('input-prefix 标识', { exact: true }).fill('问')
    await expect(host.locator('[slot=input-prefix]')).toHaveText('问')
    await toggle('sender-footer').check()
    await page.getByLabel('sender-footer 内容', { exact: true }).fill('请勿发送密码')
    await expect(host.locator('[slot=sender-footer]')).toHaveText('请勿发送密码')
    await toggle('sender-footer-right').check()
    await expect(host.locator('[slot=sender-footer-right]')).toBeVisible()
    await toggle('prompts-footer').check()
    await host.getByRole('button', { name: '换一组问题', exact: true }).click()
    await expect(host.getByText('如何使用普通 Slot？', { exact: true })).toBeVisible()
    await toggle('sender-header').uncheck()
    await expect(host.locator('.tr-sender-header')).toHaveCount(0)
    await expect(host.locator('[slot=input-prefix]')).toHaveText('问')
    await toggle('sender-header').check()
    await expect(host.locator('[slot=sender-header]')).toContainText('独立配置')
  })

  test(`${kind} Scoped Slot 逐项启用并保留其他配置与草稿`, async ({ page }) => {
    await page.goto('/#/content/scoped-slots')
    await page.getByRole('combobox', { name: '组件', exact: true }).selectOption(kind)
    const host = page.locator('[data-scoped-host]')
    const toggle = (name: string) => page.getByRole('checkbox', { name: `${name} ·`, exact: false })
    await expect(toggle('layout-header')).toBeChecked()
    await expect(toggle('layout-empty-state')).not.toBeChecked()
    await toggle('sender-footer').check()
    await page.getByLabel('sender-footer 追问内容', { exact: true }).fill('请列出接入步骤')
    await host.getByRole('button', { name: '插入追问', exact: true }).click()
    await toggle('sender-content').check()
    const input = host.getByRole('textbox', { name: '自定义输入框', exact: true })
    await expect(input).toHaveValue('请列出接入步骤')
    await toggle('sender-footer-right').check()
    await host.getByRole('button', { name: '聚焦输入框', exact: true }).click()
    await expect(input).toBeFocused()
    await toggle('layout-empty-state').check()
    await page.getByLabel('layout-empty-state 标题', { exact: true }).fill('开始账号咨询')
    await expect(host.getByRole('heading', { name: '开始账号咨询', exact: true })).toBeVisible()
    await expect(input).toHaveValue('请列出接入步骤')
    await page.getByRole('checkbox', { name: '显示欢迎区', exact: true }).uncheck()
    await toggle('bubble-prefix').check()
    await expect(host.locator('.demo-message-meta')).toHaveCount(2)
    await toggle('bubble-suffix').check()
    await expect(host.locator('.demo-message-status')).toHaveText(['已发送', '已回复'])
    await toggle('bubble-content-footer').check()
    await page.getByLabel('bubble-content-footer 来源', { exact: true }).fill('接入指南')
    await expect(host.locator('.demo-message-source')).toHaveText(['接入指南 · 消息 0', '接入指南 · 消息 1'])
    await toggle('composer-before').check()
    await expect(host.locator('.demo-composer-context')).toContainText('请列出接入步骤')
    await toggle('bubble-prefix').uncheck()
    await expect(host.locator('.demo-message-meta')).toHaveCount(0)
    await expect(host.locator('.demo-message-status')).toHaveCount(2)
    await toggle('layout-header').uncheck()
    await expect(host.locator('.chat-header__title')).toHaveText('产品咨询')
    await expect(input).toHaveValue('请列出接入步骤')
  })
}
