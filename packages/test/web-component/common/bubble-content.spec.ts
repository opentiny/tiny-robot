import { expect, test } from '../support/test'

test('Bubble 正文独立配置、消息更新、事件状态与异常恢复', async ({ page }) => {
  await page.goto('/#/content/bubble-content')
  await expect(page.getByTestId('demo-title')).toHaveText('Bubble 消息正文')
  const host = page.locator('[data-bubble-demo]')
  const product = host.locator('[data-product-card]')
  await expect(product.getByRole('heading')).toHaveText('智能助手')
  await expect(host.locator('strong')).toHaveText('默认 Markdown')
  await page.getByLabel('产品名称', { exact: true }).fill('知识助手')
  await expect(product.getByRole('heading')).toHaveText('知识助手')
  await page.getByRole('button', { name: '追加内容', exact: true }).click()
  await expect(product).toContainText('更新 1')
  await product.getByRole('button', { name: '加入清单', exact: true }).click()
  await expect(product).toContainText('已加入清单')
  await expect(page.getByTestId('bubble-event')).toContainText('product-select')
  await expect(page.getByTestId('bubble-state')).toContainText('"messageIndex":1')
  await page.getByRole('checkbox', { name: 'business-quote · 引用正文', exact: true }).check()
  await expect(host.locator('[data-quote-card]')).toHaveText('消息正文由宿主框架渲染。')
  await expect(host.locator('.tr-bubble__box')).toHaveCount(3)
  await page.getByRole('checkbox', { name: '按内容项拆分气泡', exact: true }).check()
  await expect(product.getByRole('heading')).toHaveText('知识助手')
  await expect(host.locator('.tr-bubble__box')).toHaveCount(4)
  await page.getByRole('checkbox', { name: 'product-card · 产品正文', exact: true }).uncheck()
  await expect(product).toHaveCount(0)
  await expect(host.locator('[data-quote-card]')).toBeVisible()
  await expect(host.locator('strong')).toHaveText('默认 Markdown')
  await page.getByRole('checkbox', { name: 'product-card · 产品正文', exact: true }).check()
  await page.getByRole('checkbox', { name: '模拟产品正文错误', exact: true }).check()
  await expect(page.getByTestId('bubble-error')).toContainText('bubble-content')
  await expect(host.locator('[data-quote-card]')).toBeVisible()
  await page.getByRole('checkbox', { name: '模拟产品正文错误', exact: true }).uncheck()
  await expect(product.getByRole('heading')).toHaveText('知识助手')
  await page.getByRole('button', { name: '卸载元素', exact: true }).click()
  await expect(host).toHaveCount(0)
  await page.getByRole('button', { name: '挂载元素', exact: true }).click()
  await expect(product.getByRole('heading')).toHaveText('知识助手')
  await page.getByRole('checkbox', { name: '自定义未匹配正文', exact: true }).check()
  await expect(host.locator('[data-content-fallback]')).toContainText(['默认 Markdown', '原生内容继续显示'])
})
